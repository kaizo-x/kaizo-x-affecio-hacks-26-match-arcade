"use client";

import { useEffect, useMemo, useRef, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { Check, Gamepad2, Send, Sparkles, Zap } from "lucide-react";
import { Avatar } from "@/components/ui/Avatar";
import { Badge } from "@/components/ui/Badge";
import { Button } from "@/components/ui/Button";
import { useToast } from "@/context/ToastProvider";
import {
  CHIP_REPLIES,
  GENERIC_REPLIES,
  buildStarterChips,
  createChatMessage,
  pickReply,
} from "@/data/arcadeContent";
import { cn } from "@/lib/utils";
import type { ChatMessage, MatchProfile, OutcomeChip } from "@/types";

const CHIP_POPULATE_MS = 320;
const PARTNER_REPLY_MS = 1200;

function formatClock(iso: string): string {
  return new Date(iso).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
}

export interface ChatThreadProps {
  partner: MatchProfile;
  /** Outcome chips generated by the arcade games — sent as one-tap openers. */
  chips?: OutcomeChip[];
  className?: string;
}

/** Chat window with arcade outcome chips pinned to the top as one-tap icebreakers. */
export function ChatThread({ partner, chips = [], className }: ChatThreadProps) {
  const toast = useToast();
  const scrollRef = useRef<HTMLDivElement | null>(null);
  const timers = useRef<number[]>([]);
  const [messages, setMessages] = useState<ChatMessage[]>(() => [
    createChatMessage("match", `Hey! Your profile made me smile 😄 What are you up to this week?`),
  ]);
  const [draft, setDraft] = useState("");
  const [isPartnerTyping, setPartnerTyping] = useState(false);
  const [sentChipIds, setSentChipIds] = useState<string[]>([]);

  const availableChips = useMemo(
    () => (chips.length > 0 ? chips : buildStarterChips(partner)),
    [chips, partner]
  );

  const after = (ms: number, run: () => void) => {
    const id = window.setTimeout(run, ms);
    timers.current.push(id);
  };

  useEffect(() => () => timers.current.forEach((id) => window.clearTimeout(id)), []);

  useEffect(() => {
    const container = scrollRef.current;
    if (container) container.scrollTop = container.scrollHeight;
  }, [messages, isPartnerTyping]);

  const pushPartnerReply = (seed: string, tone?: OutcomeChip["tone"]) => {
    setPartnerTyping(true);
    after(PARTNER_REPLY_MS, () => {
      const pool = tone ? CHIP_REPLIES[tone] : GENERIC_REPLIES;
      setMessages((current) => [...current, createChatMessage("match", pickReply(pool, `${seed}_${current.length}`))]);
      setPartnerTyping(false);
    });
  };

  const sendChip = (chip: OutcomeChip) => {
    if (sentChipIds.includes(chip.id)) return;

    // Populate the composer first so the tap reads as "message being written".
    setDraft(chip.message);
    after(CHIP_POPULATE_MS, () => {
      setMessages((current) => [...current, createChatMessage("me", chip.message, chip.id)]);
      setSentChipIds((current) => [...current, chip.id]);
      setDraft("");
      pushPartnerReply(chip.id, chip.tone);
      toast.success("Icebreaker sent 🎮", `Your ${chip.emoji} result is now the first thing ${partner.name} sees.`);
    });
  };

  const sendDraft = () => {
    const text = draft.trim();
    if (!text) {
      toast.error("Nothing to send", "Type a message or tap an icebreaker chip above.");
      return;
    }
    setMessages((current) => [...current, createChatMessage("me", text)]);
    setDraft("");
    pushPartnerReply(text);
  };

  return (
    <div className={cn("flex flex-col gap-4", className)}>
      <div className="flex items-center justify-between gap-3 rounded-2xl border border-white/10 bg-white/5 p-3 backdrop-blur-md">
        <div className="flex min-w-0 items-center gap-3">
          <Avatar
            name={partner.name}
            photoUrl={partner.photoUrl}
            arcadeAvatarId={partner.arcadeAvatarId}
            size="sm"
            verified={partner.verification === "verified"}
          />
          <div className="min-w-0">
            <p className="truncate text-sm font-semibold text-white">
              {partner.name}, {partner.age}
            </p>
            <p className="flex items-center gap-1.5 text-[11px] text-emerald-300">
              <span className="h-1.5 w-1.5 rounded-full bg-emerald-400" />
              Online now
            </p>
          </div>
        </div>
        <Badge tone="purple" icon={Sparkles}>
          {partner.matchPercent}% match
        </Badge>
      </div>

      <div className="space-y-2">
        <p className="flex items-center gap-1.5 text-[11px] font-semibold uppercase tracking-wide text-muted">
          <Gamepad2 className="h-3.5 w-3.5" />
          Icebreaker chips
        </p>
        <div className="flex gap-2 overflow-x-auto pb-1">
          {availableChips.map((chip) => {
            const isSent = sentChipIds.includes(chip.id);
            return (
              <motion.button
                key={chip.id}
                type="button"
                whileTap={{ scale: 0.96 }}
                disabled={isSent}
                onClick={() => sendChip(chip)}
                className={cn(
                  "flex w-56 shrink-0 flex-col gap-1 rounded-2xl border p-3 text-left transition-all",
                  isSent
                    ? "border-emerald-400/30 bg-emerald-400/5 opacity-60"
                    : "border-white/10 bg-white/5 hover:-translate-y-0.5 hover:border-rose/40 hover:bg-rose/10"
                )}
              >
                <span className="flex items-center justify-between gap-2">
                  <span className="text-lg">{chip.emoji}</span>
                  {isSent ? (
                    <span className="flex items-center gap-1 text-[10px] font-semibold text-emerald-300">
                      <Check className="h-3 w-3" />
                      Sent
                    </span>
                  ) : (
                    <span className="flex items-center gap-1 text-[10px] font-semibold uppercase tracking-wide text-rose-soft">
                      <Zap className="h-3 w-3" />
                      Tap to send
                    </span>
                  )}
                </span>
                <span className="text-[11px] font-semibold leading-snug text-white">{chip.label}</span>
              </motion.button>
            );
          })}
        </div>
      </div>

      <div
        ref={scrollRef}
        className="flex h-[44vh] min-h-[260px] flex-col gap-3 overflow-y-auto rounded-2xl border border-white/10 bg-ink-deep/50 p-4"
      >
        {messages.map((message) => {
          const isMine = message.author === "me";
          return (
            <motion.div
              key={message.id}
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.2 }}
              className={cn("flex flex-col", isMine ? "items-end" : "items-start")}
            >
              <div
                className={cn(
                  "max-w-[85%] rounded-2xl px-3.5 py-2.5 text-xs leading-relaxed",
                  isMine
                    ? "rounded-br-sm bg-gradient-to-r from-rose/85 to-accent-purple/85 text-white"
                    : "rounded-bl-sm border border-white/10 bg-white/5 text-white/90",
                  message.chipId && "ring-1 ring-white/20"
                )}
              >
                {message.text}
              </div>
              <span className="mt-1 text-[10px] text-muted">
                {isMine ? "You" : partner.name} · {formatClock(message.sentAt)}
              </span>
            </motion.div>
          );
        })}

        <AnimatePresence>
          {isPartnerTyping ? (
            <motion.div
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0 }}
              className="flex items-center gap-1.5 self-start rounded-2xl rounded-bl-sm border border-white/10 bg-white/5 px-3.5 py-3"
            >
              {[0, 1, 2].map((dot) => (
                <motion.span
                  key={dot}
                  className="h-1.5 w-1.5 rounded-full bg-muted"
                  animate={{ opacity: [0.3, 1, 0.3], y: [0, -2, 0] }}
                  transition={{ duration: 1, repeat: Infinity, delay: dot * 0.15 }}
                />
              ))}
              <span className="ml-1 text-[10px] text-muted">{partner.name} is typing…</span>
            </motion.div>
          ) : null}
        </AnimatePresence>
      </div>

      <div className="flex flex-col gap-2 sm:flex-row">
        <input
          value={draft}
          onChange={(event) => setDraft(event.target.value)}
          onKeyDown={(event) => {
            if (event.key === "Enter" && !event.shiftKey) {
              event.preventDefault();
              sendDraft();
            }
          }}
          placeholder={`Message ${partner.name}…`}
          aria-label={`Message ${partner.name}`}
          className="h-11 w-full rounded-2xl border border-white/10 bg-white/5 px-4 text-sm text-white placeholder:text-slate-500 backdrop-blur-md transition-colors focus:border-accent-purple/60 focus:outline-none focus:ring-2 focus:ring-accent-purple/40"
        />
        <Button icon={Send} onClick={sendDraft} className="sm:w-auto">
          Send
        </Button>
      </div>
    </div>
  );
}
